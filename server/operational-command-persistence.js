/**
 * @param {string} commandType
 * @param {ReadonlySet<string>} financialCommands
 */
export const requiresFinancialOperationalPersistence=(commandType,financialCommands)=>
  financialCommands.has(commandType)&&!AUDIT_ONLY_EQUIPMENT_COMMANDS.has(commandType);

// Só estes 7 campos alimentam financial_titles/settlements/bank_transactions
// (buildLegacyFinancialFacts, server/financial-shadow.js:33-114) - dreSnapshots
// NÃO entra aqui de propósito: depende de employees/config/obras/equipamentos/
// rescisoes (labor-cost-engine.js, dre-projection.js) e já se auto-repara na
// leitura (ver includeDreSnapshots:false abaixo), então nunca precisa
// disparar a sincronização síncrona por si só.
export const LEGACY_FINANCIAL_FACT_FIELDS=[
  "medicoes","payments","pagsTerceiros","outrasDesp","despesasEmpresa","pedidos","transacoes",
];
/**
 * @param {Record<string, unknown> | null | undefined} before
 * @param {Record<string, unknown> | null | undefined} after
 */
export const legacyFinancialFactsChanged=(before,after)=>
  LEGACY_FINANCIAL_FACT_FIELDS.some(field=>
    JSON.stringify(before?.[field])!==JSON.stringify(after?.[field]));

// Com FIN-003 ativo, o comando financeiro precisa reler o blob somente depois
// de obter o bloqueio da linha. Isso elimina a janela entre `lerLinha()` e a
// RPC financeira em que ponto, conciliação ou outro operador podiam tornar
// seis tentativas consecutivas obsoletas.
/**
 * @param {string} commandType
 * @param {ReadonlySet<string>} financialCommands
 * @param {{engineEnforced?:boolean,directConnection?:boolean}} [options]
 */
export const requiresLockedFinancialOperationalPersistence=(
  commandType,
  financialCommands,
  {engineEnforced=false,directConnection=false}={},
)=>
  engineEnforced
  && directConnection
  && requiresFinancialOperationalPersistence(commandType,financialCommands);
